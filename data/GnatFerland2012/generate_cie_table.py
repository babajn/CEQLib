"""Emit CIE coefficients from Table 1 of Gnat & Ferland (2012), doi:10.1088/0067-0049/199/1/20."""

from math import isfinite, log10
from pathlib import Path


def read_element(element, column_count):
    rows = []
    for line in Path(__file__).with_name(f"{element}.dat").read_text().splitlines():
        fields = line.split()
        if not fields or "e+" not in fields[0]:
            continue
        if len(fields) != column_count:
            raise ValueError(f"Unexpected column count in {element}.dat: {line}")
        temperature, cie = float(fields[0]), float(fields[-1])
        if not all(isfinite(value) and value > 0 for value in (temperature, cie)):
            raise ValueError(f"Invalid CIE row in {element}.dat: {line}")
        rows.append((temperature, cie))
    return zip(*rows)


def write_array(name, values):
    values = [format(log10(value), ".17g") for value in values]
    print(f"static const double {name}[COOLING_TABLE_CIE_SIZE_T] = {{")
    for offset in range(0, len(values), 4):
        print("    " + ", ".join(values[offset:offset + 4]) + ",")
    print("};")


# Elements EQCLib does not track: log10 number abundance relative to H = 12
# (Asplund et al. 2009, Table 1, photospheric) and the Gnat & Ferland column count.
UNTRACKED = (("N", 7.83, 10), ("Ne", 7.93, 13), ("Mg", 7.60, 15),
             ("S", 7.12, 19), ("Ca", 6.34, 23), ("Fe", 7.50, 29))


def main():
    carbon_t, carbon = read_element("C", 9)
    oxygen_t, oxygen = read_element("O", 11)
    silicon_t, silicon = read_element("Si", 17)
    grids = [carbon_t, oxygen_t, silicon_t]
    untracked = [0.0]*len(carbon_t)
    for element, log_eps, columns in UNTRACKED:
        grid, cie = read_element(element, columns)
        grids.append(grid)
        abundance = 10.0**(log_eps-12.0)
        untracked = [total + abundance*value for total, value in zip(untracked, cie)]
    if (any(grid != carbon_t for grid in grids)
            or len(carbon_t) != 189 or carbon_t[0] != 1e4 or carbon_t[-1] != 1e8
            or any(right <= left for left, right in zip(carbon_t, carbon_t[1:]))):
        raise ValueError("Expected a shared, increasing 189-point grid from 1e4 to 1e8 K")

    print("/* Generated by data/GnatFerland2012/generate_cie_table.py. */")
    print("/* Table 1 of Gnat & Ferland (2012), per-element CIE cooling.")
    print("   Values are log10(T/K) and log10(Lambda / (erg cm^3 s^-1)). */")
    print(f"#define COOLING_TABLE_CIE_SIZE_T {len(carbon_t)}\n")
    for name, values in (
        ("CoolingTableCIELogT", carbon_t),
        ("CoolingTableCIELogLambdaCarbon", carbon),
        ("CoolingTableCIELogLambdaOxygen", oxygen),
        ("CoolingTableCIELogLambdaSilicon", silicon),
    ):
        write_array(name, values)
        print()
    names = ", ".join(f"{element} {log_eps:.2f}" for element, log_eps, _ in UNTRACKED)
    print("/* Sum over the untracked elements of (n_X/n_H) Lambda_X for the solar mixture of")
    print(f"   Asplund et al. (2009), log eps = {names}. It multiplies n_e n_H Z/Z_sun. */")
    write_array("CoolingTableCIELogLambdaUntrackedSolar", untracked)


if __name__ == "__main__":
    main()
